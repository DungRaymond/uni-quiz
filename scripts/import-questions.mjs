import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

export const root = fileURLToPath(new URL('../', import.meta.url));
export const source = path.resolve(root, '../lý-dược/ngan_hang_cau_hoi_ly_duoc.md');

export function parseQuestions(markdown) {
  const blocks = [...markdown.matchAll(/^### Câu (\d+)\s*\r?\n([\s\S]*?)(?=^### Câu \d+|(?![\s\S]))/gm)];
  if (!blocks.length) throw new Error('Không tìm thấy câu hỏi trong Markdown.');
  const seen = new Set();
  return blocks.map(([, number, block]) => {
    const id = `ly-duoc-${number.padStart(3, '0')}`;
    const fail = (message) => { throw new Error(`Câu ${number}: ${message}`); };
    if (seen.has(id)) fail('Mã câu bị trùng.');
    seen.add(id);
    const prompt = block.match(/^\* \*\*Nội dung:\*\* (.+)$/m)?.[1]?.trim();
    const explanation = (block.match(/^\* \*\*Giải thích:\*\* ([\s\S]*?)(?=\n---|$)/m)?.[1]
      ?? block.match(/^\* \*\*⚠️ LƯU Ý – CẦN HỎI LẠI THẦY:\*\* (.+)$/m)?.[1])?.trim();
    const options = [];
    const correct = [];
    for (const line of block.split(/\r?\n/)) {
      const match = line.match(/^\s+\* (\*\*)?([A-D])\. (.+)$/);
      if (!match) continue;
      const [, bold, key, raw] = match;
      const marker = raw.match(/\s+\*\((Đáp án đúng|Đáp án chuẩn theo giáo trình môn học|Đáp án tạm theo ghi nhận của người học|Lựa chọn chuẩn[^)]*)\)\*\s*$/);
      if (marker && !bold) fail('Đáp án đánh dấu không đúng định dạng.');
      let text = marker ? raw.slice(0, marker.index).trim() : raw.trim();
      if (bold) {
        if (!text.endsWith('**')) fail(`Lựa chọn ${key} thiếu dấu đóng in đậm.`);
        text = text.slice(0, -2);
      }
      if (!text) fail(`Lựa chọn ${key} trống.`);
      options.push({ key, text });
      if (marker) correct.push(key);
    }
    if (!prompt || !explanation) fail('Thiếu nội dung hoặc giải thích.');
    if (options.map((option) => option.key).join('') !== 'ABCD') fail('Phải có đúng bốn lựa chọn A–D.');
    if (correct.length !== 1) fail('Phải đánh dấu đúng một đáp án.');
    const exclusionReason = block.includes('Câu hỏi lỗi đề thi') ? 'Đề gốc ghép sai nội dung và đáp án; cần duyệt lại.'
      : block.includes('Đáp án tạm theo ghi nhận') ? 'Đáp án tạm thời; cần hỏi lại giảng viên.' : null;
    return { id, sourceNumber: Number(number), prompt, options, correctKey: correct[0], explanation, active: exclusionReason === null,
      exclusionReason };
  });
}

export function createSeed(questions) {
  const quote = (value) => `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
  return `-- Generated by npm run import:questions. Do not edit.\nbegin;\n` + questions.map((question) => {
    const publicData = { sourceNumber: question.sourceNumber, prompt: question.prompt, options: question.options };
    return `insert into public.questions (id, data, active, exclusion_reason) values ('${question.id}', ${quote(publicData)}, ${question.active}, ${question.exclusionReason ? "'" + question.exclusionReason.replaceAll("'", "''") + "'" : 'null'}) on conflict (id) do update set data = excluded.data, active = excluded.active, exclusion_reason = excluded.exclusion_reason;\ninsert into public.question_answer_keys (question_id, correct_key, explanation) values ('${question.id}', '${question.correctKey}', '${question.explanation.replaceAll("'", "''")}') on conflict (question_id) do update set correct_key = excluded.correct_key, explanation = excluded.explanation;`;
  }).join('\n') + '\ncommit;\n';
}

async function main() {
  const questions = parseQuestions(await readFile(source, 'utf8'));
  const active = questions.filter((question) => question.active).length;
  if (active < 30) throw new Error('Ngân hàng phải có ít nhất 30 câu hợp lệ.');
  if (!process.argv.includes('--check')) {
    await mkdir(path.join(root, 'supabase'), { recursive: true });
    await writeFile(path.join(root, 'supabase/seed.sql'), createSeed(questions));
  }
  console.log(`${questions.length} câu nguồn; ${active} câu dùng được; ${questions.length - active} câu cần duyệt.`);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => { console.error(error.message); process.exitCode = 1; });
}
